CREATE OR REPLACE FUNCTION public.handle_batch_fee_assignment()
RETURNS TRIGGER AS $$
BEGIN
    -- Automatically assign the new fee to all students in the target batch
    INSERT INTO public.student_fee_assignments (
        fee_assignment_id,
        student_id,
        amount,
        paid_amount,
        outstanding_amount,
        due_date,
        status,
        academic_year,
        created_at
    )
    SELECT 
        NEW.id,
        s.id,
        NEW.amount,
        0,
        NEW.amount,
        NEW.due_date,
        'Unpaid',
        NEW.academic_year,
        now()
    FROM public.students s
    WHERE s.batch = NEW.batch
    ON CONFLICT DO NOTHING;

    -- Also mirror into student_fees for student dashboard view
    INSERT INTO public.student_fees (
        student_id,
        title,
        category,
        total_amount,
        paid_amount,
        outstanding_amount,
        due_date,
        status,
        academic_year,
        created_at
    )
    SELECT 
        s.id,
        NEW.fee_name,
        NEW.fee_type,
        NEW.amount,
        0,
        NEW.amount,
        NEW.due_date,
        'Unpaid',
        NEW.academic_year,
        now()
    FROM public.students s
    WHERE s.batch = NEW.batch
    ON CONFLICT DO NOTHING;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

